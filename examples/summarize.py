"""Turn the demo outputs (selection / labels / eval) into one markdown table.

Every number is read from the generated JSON files -- nothing here is typed by
hand, so re-running the demo and this script refreshes the table faithfully.

    python3 examples/summarize.py --run charuco:examples/charuco/work \
        --run ycbv:examples/ycbv/work --out examples/demo_results.md
"""
import argparse
import datetime
import json
import os
import sys


def _j(path):
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)


def _fmt(x, nd=3):
    return "--" if x is None else ("%.*f" % (nd, x))


def _row(label, val):
    return "| %s | %s |" % (label, val)


def summarize_run(name, work):
    sel = _j(os.path.join(work, "selection.json"))
    lab = _j(os.path.join(work, "labels", "summary.json"))
    ev = _j(os.path.join(work, "eval.json"))
    o, r = ev["ours"], ev.get("random", {})
    lines = []
    lines.append("## %s" % name)
    lines.append("")
    lines.append("| item | value |")
    lines.append("|---|---|")
    lines.append(_row("rendered frames", "%d" % lab["n_frames"]))
    lines.append(_row("candidate frames (pose + model, margin %s px)"
                      % _fmt(sel.get("margin_px"), 0), "%d" % sel["n_candidates"]))
    lines.append(_row("Theta_span", "%s deg" % _fmt(sel["theta_span_deg"], 2)))
    lines.append(_row("N_sat = ceil(Theta / (2*theta_eff))",
                      "%d  (theta_eff %s deg)" % (sel["n_sat"], _fmt(sel["theta_eff_deg"], 2))))
    lines.append(_row("selected views", "%d  (guard %s deg, theta_max %s deg)"
                      % (sel["n_selected"], _fmt(sel["guard_deg"], 1),
                         _fmt(sel["theta_max_deg"], 2))))
    lines.append(_row("points triangulated", "%d  (min %s clicks per point)"
                      % (ev["n_points"], ev.get("min_views", "?"))))
    lines.append(_row("annotated-view residual (median / mean / max)",
                      "%s / %s / %s px" % (_fmt(lab["resid_px"]["median"]),
                                           _fmt(lab["resid_px"]["mean"]),
                                           _fmt(lab["resid_px"]["max"]))))
    lines.append(_row("held-out 2D, ours (median / mean / p90)",
                      "%s / %s / %s px  (n=%d)"
                      % (_fmt(o["median"]), _fmt(o["mean"]), _fmt(o["p90"]), o["n_obs"])))
    if "trial_median" in r:
        lines.append(_row("held-out 2D, random %d views x %d trials, "
                          "trial medians (median / mean over trials)"
                          % (r["n_views"], r["trials"]),
                          "%s / %s px" % (_fmt(r["trial_median"]["median"]),
                                          _fmt(r["trial_median"]["mean"]))))
        lines.append(_row("held-out 2D, random, trial means (median / mean over trials)",
                          "%s / %s px" % (_fmt(r["trial_mean"]["median"]),
                                          _fmt(r["trial_mean"]["mean"]))))
        lines.append(_row("random win rate for ours (median / mean criterion)",
                          "%s%% / %s%%" % (_fmt(100 * r["win_rate_median"], 0),
                                           _fmt(100 * r["win_rate_mean"], 0))))
        lines.append(_row("paired difference ours - random on trial medians (median / mean over trials)",
                          "%s / %s px" % (_fmt(r["diff_median"]["median"]),
                                          _fmt(r["diff_median"]["mean"]))))
        lines.append(_row("paired difference ours - random on trial means (median / mean over trials)",
                          "%s / %s px" % (_fmt(r["diff_mean"]["median"]),
                                          _fmt(r["diff_mean"]["mean"]))))
    g = ev.get("gt3d", {})
    if "loo_mm" in g:
        lines.append(_row("3D vs GT, Sim(3) LOO (median / mean), %d points" % g["n_points"],
                          "%s / %s mm  (scale %s mm/unit)"
                          % (_fmt(g["loo_mm"]["median"]), _fmt(g["loo_mm"]["mean"]),
                             _fmt(g["scale_mm_per_unit"], 3))))
    lines.append("")
    return lines


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--run", action="append", required=True,
                    help="name:work_dir, e.g. charuco:examples/charuco/work")
    ap.add_argument("--out", default=None)
    a = ap.parse_args(argv)

    lines = ["# Demo results (generated)", "",
             "Generated by `examples/summarize.py` on %s from the JSON files of "
             "the demo runs; rerun the demos and this script to refresh."
             % datetime.date.today().isoformat(), ""]
    for spec in a.run:
        name, _, work = spec.partition(":")
        if not work:
            raise SystemExit("--run expects name:work_dir, got %r" % spec)
        lines += summarize_run(name, work)
    text = "\n".join(lines)
    if a.out:
        os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
        with open(a.out, "w", encoding="utf-8") as fh:
            fh.write(text + "\n")
        print("wrote", a.out)
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
